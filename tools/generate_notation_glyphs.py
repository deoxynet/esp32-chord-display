"""Generate the small staff glyph subset; font is a build-time input only.

Source: Bravura 1.482, https://github.com/steinbergmedia/bravura/releases/tag/bravura-1.482
Usage: uv run tools/generate_notation_glyphs.py build/notation-font/Bravura.otf
"""
from pathlib import Path
import hashlib
import sys
from PIL import Image, ImageDraw, ImageFont

source = Path(sys.argv[1])
expected = "cdf0f893ee1fdb64b7f6713d71ee0dcfc349c0ac01429a8e451b01a9e79f5f3b"
if hashlib.sha256(source.read_bytes()).hexdigest() != expected:
    raise SystemExit("Expected the pinned Bravura 1.482 font")
font = ImageFont.truetype(str(source), 40)  # four ten-pixel staff spaces per em
glyphs = {"trebleClef": 0xE050, "bassClef": 0xE062, "notehead": 0xE0A4,
          "flat": 0xE260, "natural": 0xE261, "sharp": 0xE262,
          "doubleSharp": 0xE263, "doubleFlat": 0xE264}
lines = ["// Generated by tools/generate_notation_glyphs.py from Bravura 1.482.",
         "// Glyph subset: Chord Staff Glyphs. Copyright Steinberg Media Technologies GmbH.",
         "// SIL Open Font License 1.1; see ../NOTATION-LICENSE.txt.",
         "#pragma once", "#include <cstdint>", "namespace chord::staffglyph {",
         "struct Glyph { int left, top, width, height; const uint32_t* rows; };"]
for name, codepoint in glyphs.items():
    char = chr(codepoint)
    left, top, right, bottom = font.getbbox(char, anchor="ls")
    image = Image.new("L", (right-left, bottom-top))
    ImageDraw.Draw(image).text((-left, -top), char, font=font, anchor="ls", fill=255)
    box = image.point(lambda p: 255 if p >= 100 else 0).getbbox()
    if box:
        image = image.crop(box)
        left += box[0]; top += box[1]
    if image.width > 32:
        raise SystemExit("Glyph exceeds the bounded row mask")
    rows = [sum(1 << x for x in range(image.width) if image.getpixel((x,y)) >= 100)
            for y in range(image.height)]
    lines.append(f"inline constexpr uint32_t {name}Rows[] = {{")
    for start in range(0, len(rows), 8):
        lines.append("    " + ", ".join(f"0x{r:08x}U" for r in rows[start:start+8]) + ",")
    lines += ["};", f"inline constexpr Glyph {name} = {{{left}, {top}, {image.width}, {image.height}, {name}Rows}};"]
    print(name, left, top, image.width, image.height)
lines += ["inline const Glyph& accidental(int value) {",
          "    switch (value) { case -2: return doubleFlat; case -1: return flat;",
          "        case 1: return sharp; case 2: return doubleSharp; default: return natural; }", "}", "}"]
target = Path(__file__).resolve().parents[1] / "lib/ChordApp/src/NotationGlyphs.h"
target.write_text("\n".join(lines)+"\n")
